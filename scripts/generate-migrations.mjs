#!/usr/bin/env node
/**
 * Embeds the migration SQL into TypeScript so applying migrations never depends on a
 * filesystem path.
 *
 * `applyMigrations` used to resolve `../migrations` from its own module URL, which is
 * correct only when the code runs from its source tree. Bundled into a binary, or copied
 * into a container image, that path points somewhere else and the process dies on start
 * with ENOENT — a failure the whole test suite cannot see, because tests always run from
 * the source tree.
 *
 * The .sql files stay the source of truth: they are what a reviewer reads and what a
 * database tool can run directly. This script copies them into a module, and a test
 * asserts the two never drift.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const migrationsDir = join(root, "packages/db/migrations")
const target = join(root, "packages/db/src/migrations.generated.ts")

const files = readdirSync(migrationsDir).filter((f) => f.endsWith(".sql")).toSorted()

const entries = files
  .map((name) => {
    const sql = readFileSync(join(migrationsDir, name), "utf8")
    const escaped = sql.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${")
    return `  {\n    name: ${JSON.stringify(name)},\n    sql: \`${escaped}\`,\n  },`
  })
  .join("\n")

writeFileSync(
  target,
  `// GENERATED by scripts/generate-migrations.mjs — do not edit by hand.
// Run \`pnpm generate:migrations\` after changing anything under packages/db/migrations.
//
// The SQL lives here as well as in the .sql files so applying migrations never depends
// on a filesystem path. A path relative to the module works only when running from the
// source tree; bundled or containerised it points elsewhere and the process dies on
// start — which no test can catch, because tests always run from the source tree.

export type Migration = { name: string; sql: string }

export const MIGRATIONS: Migration[] = [
${entries}
]
`,
)
console.log(`wrote ${target} (${files.length} migration${files.length === 1 ? "" : "s"})`)
